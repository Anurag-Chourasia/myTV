#!/usr/bin/env python3

import re
import sys
from pathlib import Path
from typing import Dict, List

# -----------------------
# Configuration
# -----------------------

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent  # myTV/myTV

LOCALIZABLE_FILE = (
    PROJECT_ROOT
    / "Resources"
    / "Localization"
    / "Base.lproj"
    / "Localizable.strings"
)

OUTPUT_FILE = (
    PROJECT_ROOT
    / "Resources"
    / "Localization"
    / "Localizable.generated.swift"
)

if not LOCALIZABLE_FILE.exists():
    raise FileNotFoundError(
        f"❌ Missing Localizable.strings at {LOCALIZABLE_FILE}"
    )

HEADER = """// ⚠️ AUTO-GENERATED — DO NOT EDIT
// Generated by generate_localization.py
//
// This file is generated from Localizable.strings.
// Any manual changes will be overwritten.
//

import Foundation
"""

# -----------------------
# Utilities
# -----------------------

SWIFT_KEYWORDS = {
    "class", "struct", "enum", "protocol", "extension",
    "func", "var", "let", "import", "static", "case",
    "default", "switch", "if", "else", "for", "while",
    "return", "break", "continue", "do", "try", "catch",
    "throw", "throws", "rethrows", "in", "where",
}

def sanitize_identifier(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_]", "_", value)
    if value[0].isdigit():
        value = "_" + value
    if value in SWIFT_KEYWORDS:
        value += "_"
    return value

def upper_camel(value: str) -> str:
    parts = re.split(r"[._-]", value)
    return "".join(sanitize_identifier(p).capitalize() for p in parts)

def lower_camel(value: str) -> str:
    parts = re.split(r"[._-]", value)
    first = sanitize_identifier(parts[0])
    rest = [sanitize_identifier(p).capitalize() for p in parts[1:]]
    return first + "".join(rest)

# -----------------------
# Parsing
# -----------------------

def parse_keys(path: Path) -> List[str]:
    if not path.exists():
        sys.exit(f"❌ Missing Localizable.strings at {path}")

    pattern = re.compile(r'^\s*"([^"]+)"\s*=')
    keys = []

    for line in path.read_text(encoding="utf-8").splitlines():
        match = pattern.match(line)
        if match:
            keys.append(match.group(1))

    if not keys:
        sys.exit("❌ No localization keys found")

    return sorted(set(keys))

def build_tree(keys: List[str]) -> Dict:
    tree: Dict = {}
    for key in keys:
        parts = key.split(".")
        node = tree
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node.setdefault("__values__", []).append(parts[-1])
    return tree

# -----------------------
# Swift Generation
# -----------------------

def emit_enum(
    name: str,
    node: Dict,
    path: List[str],
    indent: int
) -> List[str]:
    pad = " " * indent
    lines = [f"{pad}enum {upper_camel(name)} {{"]

    # Nested enums
    for child in sorted(k for k in node.keys() if k != "__values__"):
        lines.extend(
            emit_enum(child, node[child], path + [child], indent + 4)
        )

    # Values
    for value in sorted(node.get("__values__", [])):
        key = ".".join(path + [value])
        prop = lower_camel(value)

        lines.append(f"{pad}    static let {prop} = NSLocalizedString(")
        lines.append(f'{pad}        "{key}",')
        lines.append(f'{pad}        comment: ""')
        lines.append(f"{pad}    )")

    lines.append(f"{pad}}}")
    return lines

def generate_swift(tree: Dict) -> str:
    lines = [HEADER, "enum Localizable {"]

    for top in sorted(tree.keys()):
        lines.extend(emit_enum(top, tree[top], [top], 4))

    lines.append("}")
    lines.append("")
    return "\n".join(lines)

# -----------------------
# Entry Point
# -----------------------

def main():
    keys = parse_keys(LOCALIZABLE_FILE)
    tree = build_tree(keys)
    swift = generate_swift(tree)

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(swift, encoding="utf-8")

    print(f"✅ Generated {OUTPUT_FILE}")
    print(f"🔑 {len(keys)} localization keys processed")

if __name__ == "__main__":
    main()
